// Makes src/renderer/settings-manifest.ts from the engine's companion/settings_manifest.json (every engine setting's
// default, range and how a change applies), so the Settings page and the engine can't disagree. Run by npm run build
// before tsc; `node scripts/gen-settings.js --check` only says whether the .ts is up to date (exit 1 when not).
const fs = require("fs");
const path = require("path");

const desk = path.join(__dirname, "..");
const src = path.join(desk, "..", "companion", "settings_manifest.json");
const out = path.join(desk, "src", "renderer", "settings-manifest.ts");

const manifest = JSON.parse(fs.readFileSync(src, "utf8")).settings;
const lines = Object.entries(manifest).map(([k, e]) => {
  const keep = {};
  for (const f of ["default", "min", "max", "kind", "live", "app"]) if (e[f] !== undefined) keep[f] = e[f];
  return `  ${JSON.stringify(k)}: ${JSON.stringify(keep)},`;
});
const text = `// Generated by scripts/gen-settings.js from companion/settings_manifest.json (npm run build): edit that file.
// Each engine setting by its path under config.json "companion": its default, range, kind, and how a change applies
// (live: the coach takes it at once; app: the app acts on it itself; neither: after a coach restart).

export interface ManifestEntry {
  default: unknown;
  min?: number;
  max?: number;
  kind: "int" | "number" | "bool" | "text" | "list";
  live?: boolean;
  app?: boolean;
}

export const MANIFEST: Record<string, ManifestEntry> = {
${lines.join("\n")}
};
`;

const now = fs.existsSync(out) ? fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") : "";   // CRLF: the same file
if (process.argv.includes("--check")) {
  if (now !== text) {
    console.error("src/renderer/settings-manifest.ts is out of date: run node scripts/gen-settings.js");
    process.exit(1);
  }
  console.log("ok");
} else if (now !== text) {
  fs.writeFileSync(out, text);
}

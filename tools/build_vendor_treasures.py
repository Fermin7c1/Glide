#!/usr/bin/env python3
"""Generate addon/Glide/Data/VendorTreasures.lua from RestedXP's copy of Cpt. Stadics' Vendor Treasures.

The source is CptStadicsVendorTreasures.lua in the installed RestedXP addon (Interface/AddOns/RXPGuides): vendors
that sell limited-stock gear or potions worth buying while levelling, with zone, position, faction and item ids. The
data is Creative Commons Attribution-NonCommercial 3.0 (https://creativecommons.org/licenses/by-nc/3.0/): the
generated file keeps the attribution, and Glide is free and non-commercial.

Usage: python tools/build_vendor_treasures.py [path to CptStadicsVendorTreasures.lua or the WoW folder]
"""
import json
import os
import re
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "addon", "Glide", "Data", "VendorTreasures.lua")
SOURCE = "CptStadicsVendorTreasures.lua"

_ZONE = re.compile(r"local\s+(ZONE_\w+)\s*=\s*(\d+)")
_ENTRY = re.compile(r"SetZoneNPCData\(\s*(ZONE_\w+)\s*,\s*L?\s*\"((?:[^\"\\]|\\.)*)\"\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*,"
                    r"\s*(CLASS_\w+)\s*,\s*(\w+)\s*,\s*\{([^}]*)\}", re.S)
KIND = {"CLASS_GEAR": "G", "CLASS_POTION": "P"}
FACTION = {"ALLIANCE": "A", "HORDE": "H", "NEUTRAL": "N"}


def parse(text):
    """[(ui_map, x, y, name, kind G|P, faction A|H|N, [item ids])] from the source file."""
    zones = {k: int(v) for k, v in _ZONE.findall(text)}
    out = []
    for z, name, x, y, cls, fac, items in _ENTRY.findall(text):
        if z not in zones or cls not in KIND or fac not in FACTION:
            continue
        ids = [int(i) for i in re.findall(r"\d+", items)]
        if ids:
            out.append((zones[z], round(float(x), 1), round(float(y), 1), name.replace('\\"', '"'), KIND[cls],
                        FACTION[fac], ids))
    return out


def lua(entries):
    lines = ["-- Vendor treasures: vendors with limited-stock gear and potions worth buying while levelling.",
             "-- Generated by tools/build_vendor_treasures.py from RestedXP's copy of Cpt. Stadics' Vendor Treasures",
             "-- (https://www.curseforge.com/wow/addons/cpt-stadics-map-of-vendor-treasures), licensed Creative Commons",
             "-- Attribution-NonCommercial 3.0 (https://creativecommons.org/licenses/by-nc/3.0/).",
             "-- Entry: { uiMap, x, y, name, kind (G gear, P potions), faction (A, H, N neutral), { item ids } }",
             "local _, ns = ...",
             "ns.VENDOR_TREASURES = {"]
    for m, x, y, name, kind, fac, ids in entries:
        lines.append("    { %d, %s, %s, %s, %s, %s, { %s } }," % (m, x, y, json.dumps(name), json.dumps(kind),
                                                              json.dumps(fac), ", ".join(map(str, ids))))
    lines.append("}")
    return "\n".join(lines) + "\n"


def find_source(arg):
    if arg and os.path.isfile(arg):
        return arg
    wow = arg
    if not wow:
        if os.path.join(ROOT, "companion") not in sys.path:
            sys.path.append(os.path.join(ROOT, "companion"))
        import glideconfig
        wow = glideconfig.wow_dir(ROOT)
    p = os.path.join(wow or "", "Interface", "AddOns", "RXPGuides", SOURCE)
    return p if os.path.isfile(p) else None


def main(argv):
    src = find_source(argv[1] if len(argv) > 1 else None)
    if not src:
        print("RestedXP's %s not found (pass the file or the WoW folder)" % SOURCE)
        return 1
    with open(src, encoding="utf-8", errors="replace") as fh:
        entries = parse(fh.read())
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(lua(entries))
    print("%d vendors -> %s" % (len(entries), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
